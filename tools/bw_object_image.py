#!/usr/bin/env python3
"""The machine code of the Broadway kernel objects (port/wiiu/src/bw, assembled by devkitPPC), as C data for the instruction simulator
(port/wiiu/tests/gekko_sim.h): for each object its code, its read-only constants, the relocations of the code against them (the
high and low halves of an address: the only relocations the kernels have) and its functions.

    bw_object_image.py OBJECT... > bw_image.h
"""

import struct
import sys

R_PPC_ADDR16_LO = 4
R_PPC_ADDR16_HA = 6


def sections_of(data):
    if data[:7] != b"\x7fELF\x01\x02\x01":
        raise SystemExit("not a big-endian ELF32 object")
    shoff, = struct.unpack_from(">I", data, 32)
    shentsize, shnum, shstrndx = struct.unpack_from(">HHH", data, 46)
    sections = []
    for index in range(shnum):
        name, kind, flags, address, offset, size, link, info, align, entsize = struct.unpack_from(">10I", data, shoff + index * shentsize)
        sections.append(dict(name_offset=name, kind=kind, flags=flags, offset=offset, size=size, link=link, info=info, entsize=entsize, index=index))
    names = sections[shstrndx]
    for section in sections:
        start = names["offset"] + section["name_offset"]
        section["name"] = data[start:data.index(b"\0", start)].decode()
        section["data"] = data[section["offset"]:section["offset"] + section["size"]] if section["kind"] != 8 else b""
    return sections


def describe(path):
    data = open(path, "rb").read()
    sections = sections_of(data)
    text = [s for s in sections if s["name"].startswith(".text.halo_bw") and s["kind"] == 1]
    rodata = [s for s in sections if s["name"].startswith(".rodata.halo_bw") and s["kind"] == 1]
    if len(text) != 1 or len(rodata) > 1:
        raise SystemExit(f"{path}: expected one text and at most one rodata section")
    text = text[0]
    symtab = next(s for s in sections if s["kind"] == 2)
    strings = sections[symtab["link"]]["data"]
    functions = []
    symbols = []
    for at in range(0, symtab["size"], 16):
        name, value, size, info, other, shndx = struct.unpack_from(">IIIBBH", symtab["data"], at)
        symbols.append(shndx)
        if shndx == text["index"] and info & 15 == 2:
            functions.append((strings[name:strings.index(b"\0", name)].decode(), value))
    relocations = []
    for section in sections:
        if section["kind"] == 4 and section["info"] == text["index"]:
            for at in range(0, section["size"], 12):
                offset, info, addend = struct.unpack_from(">IIi", section["data"], at)
                kind, symbol = info & 0xff, info >> 8
                if kind not in (R_PPC_ADDR16_HA, R_PPC_ADDR16_LO) or not rodata or symbols[symbol] != rodata[0]["index"] or addend:
                    raise SystemExit(f"{path}: a relocation the simulator does not do (type {kind} at {offset:#x})")
                relocations.append((offset, "H" if kind == R_PPC_ADDR16_HA else "L"))
    return text["data"], rodata[0]["data"] if rodata else b"", relocations, functions


def main():
    print("/* generated by tools/bw_object_image.py from the kernel objects: do not edit */")
    objects = []
    for path in sys.argv[1:]:
        code, constants, relocations, functions = describe(path)
        stem = path.rsplit("/", 1)[-1].replace(".o", "")
        words = struct.unpack(">%dI" % (len(code) // 4), code)
        print(f"static const unsigned {stem}_code[] = {{ " + ", ".join(f"0x{w:08x}u" for w in words) + " };")
        print(f"static const unsigned char {stem}_constants[] = {{ " + (", ".join(str(b) for b in constants) or "0") + " };")
        print(f"static const struct bw_relocation {stem}_relocations[] = {{ "
              + (", ".join(f"{{ {o}, '{k}' }}" for o, k in relocations) or "{ 0, 0 }") + " };")
        print(f"static const struct bw_function {stem}_functions[] = {{ " + ", ".join(f'{{ "{n}", {v // 4} }}' for n, v in functions) + " };")
        objects.append((stem, len(words), len(constants), len(relocations), len(functions)))
    print("static const struct bw_object bw_objects[] = {")
    for stem, words, constants, relocations, functions in objects:
        print(f'\t{{ "{stem}", {stem}_code, {words}, {stem}_constants, {constants}, {stem}_relocations, {relocations}, {stem}_functions, {functions} }},')
    print("};")


if __name__ == "__main__":
    main()
