#!/usr/bin/env python3
"""Defines every symbol the Wii U link still lacks as a stub that names itself and stops.

The Wii U build (tools/wiiu_build.py) compiles the game and the platform layer that exists, and the platform layer
that would make it run is not all written. This asks the linker itself what is undefined (linking the objects as the
build does, without discarding unreferenced sections, and with unresolved symbols reported rather than fatal) and
writes a C source that defines each: a function that reports its name (OSReport, then OSFatal) and does not return;
for a name only an address is taken of and no call is made, an array of zeros (a table, or a variable), as large as
the biggest the game declares. The link then completes, the RPX starts the game, and the first thing the game needs
that is not there ends the run with its name on the screen. Writing the real function removes its stub: this is
regenerated whenever the objects change, and only what is still undefined is stubbed.

Also writes the list of the stubs (name and F or D), which is what tools/wiiu_stubs.py --compare checks against the
committed baseline (port/wiiu/stubbed_symbols.txt): a symbol that became undefined is a regression, and one that a
unit now defines is progress, to be taken off the baseline.

    wiiu_stubs.py --link "powerpc-eabi-gcc FLAGS" --libs "LIBS" --objects RESPONSE_FILE --output stubs.c --list stubs.txt
    wiiu_stubs.py --compare stubs.txt port/wiiu/stubbed_symbols.txt
"""

import argparse
import re
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, Set

# a call is a function; a reference that only takes an address could be a table or a function pointer
CALL_RELOCATIONS = {"R_PPC_REL24", "R_PPC_PLTREL24"}
# functions whose address is taken and that nothing in the objects calls
FUNCTION_POINTERS = {"mbedtls_platform_entropy_poll"}
# the biggest of the tables and variables stubbed as data (D3D__RenderState, D3D__TextureState, the device tables)
DATA_BYTES = 65536
READELF = "llvm-readelf"

HEADER = """/* Generated by tools/wiiu_stubs.py: the symbols the Wii U link lacks, {count} of them ({functions} functions, {data} tables).
Each function names itself and stops; writing the real one removes its stub. Do not edit. */

#include <coreinit/debug.h>
#include <coreinit/thread.h>
#include <coreinit/time.h>
#include <sysapp/launch.h>

/* the shell's log (port/wiiu/src/wiiu_shell.c): the card is where the Mac reads it from */
void wiiu_log_text(const char *text);

/* Names itself in the log and on the debug output, then asks for the Wii U Menu: the app ends as any app does, and the console
stays usable (OSFatal would keep its error screen until the power button). */
static void __attribute__((noreturn, unused)) wiiu_missing(const char *message)
{{
	OSReport("%s\\n", message);
	wiiu_log_text(message);
	wiiu_log_text("\\n");
	OSSleepTicks(OSMillisecondsToTicks(1500));
	SYSLaunchMenu();
	for (;;)
	{{
		OSSleepTicks(OSMillisecondsToTicks(100));
	}}
}}

#define FUNCTION_STUB(name) \\
	void name(void) \\
	{{ \\
		wiiu_missing("OpenCE: " #name " is not implemented on the Wii U yet"); \\
	}}
#define DATA_STUB(name) unsigned char name[{data_bytes}] __attribute__((aligned(16)));

"""


def objects_of(response: Path) -> List[str]:
    return [path for line in response.read_text().splitlines() for path in shlex.split(line)]


def undefined_symbols(link: str, libs: str, response: Path) -> Set[str]:
    """what ld cannot find, linking the response file's objects"""
    with tempfile.TemporaryDirectory() as folder:
        command = (f"{link} -Wl,--unresolved-symbols=report-all -Wl,--noinhibit-exec -Wl,--no-gc-sections "
                   f"@{shlex.quote(str(response))} {libs} -o {shlex.quote(folder + '/probe.elf')}")
        result = subprocess.run(command, shell=True, capture_output=True, text=True)
    names = set(re.findall(r"undefined reference to `([^']+)'", result.stderr))
    if not names and result.returncode != 0:
        sys.exit(f"the link failed without naming an undefined symbol:\n{result.stderr[-3000:]}")
    return names


def called(names: Set[str], objects: List[str]) -> Set[str]:
    """those of the names that some object calls (a PowerPC branch to it), by the objects' relocations"""
    found: Set[str] = set()
    if not names:
        return found
    process = subprocess.Popen([READELF, "-r", "--wide", *objects], stdout=subprocess.PIPE, text=True)
    assert process.stdout is not None
    for line in process.stdout:
        fields = line.split()
        # "00000010  0000151a R_PPC_REL24  00000000  CloseHandle + 0"
        if len(fields) >= 5 and fields[2] in CALL_RELOCATIONS and fields[4] in names:
            found.add(fields[4])
    if process.wait() != 0:
        sys.exit(f"{READELF} failed")
    return found


def kinds(names: Set[str], objects: List[str]) -> Dict[str, str]:
    """F for a function, D for a table or variable"""
    calls = called(names, objects)
    return {name: "F" if name in calls or name in FUNCTION_POINTERS else "D" for name in sorted(names)}


def write_stubs(kind: Dict[str, str], output: Path, listing: Path) -> None:
    functions = sum(1 for k in kind.values() if k == "F")
    lines = [HEADER.format(count=len(kind), functions=functions, data=len(kind) - functions, data_bytes=DATA_BYTES)]
    for name, k in kind.items():
        lines.append(f"{'FUNCTION_STUB' if k == 'F' else 'DATA_STUB'}({name})\n")
    output.write_text("".join(lines))
    listing.write_text("".join(f"{name} {k}\n" for name, k in kind.items()))


def read_names(path: Path) -> Set[str]:
    return {line.split()[0] for line in path.read_text().splitlines() if line.strip() and not line.startswith("#")}


def compare(listing: Path, baseline: Path) -> int:
    now, before = read_names(listing), read_names(baseline)
    new, gone = sorted(now - before), sorted(before - now)
    print(f"{len(now)} symbols stubbed; the baseline has {len(before)}")
    for name in new:
        print(f"NEWLY MISSING {name}")
    for name in gone:
        print(f"NOW DEFINED {name} (take it off {baseline})")
    return 1 if new or gone else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--link", help="the link command up to the objects, with its flags")
    parser.add_argument("--libs", default="", help="the libraries, after the objects")
    parser.add_argument("--objects", type=Path, help="the response file listing the objects")
    parser.add_argument("--output", type=Path, help="the C source to write")
    parser.add_argument("--list", type=Path, help="the list of stubs to write")
    parser.add_argument("--compare", nargs=2, type=Path, metavar=("LIST", "BASELINE"))
    args = parser.parse_args()
    if args.compare:
        return compare(*args.compare)
    if not (args.link and args.objects and args.output and args.list):
        parser.error("--link, --objects, --output and --list are needed")
    objects = objects_of(args.objects)
    names = undefined_symbols(args.link, args.libs, args.objects)
    write_stubs(kinds(names, objects), args.output, args.list)
    return 0


if __name__ == "__main__":
    sys.exit(main())
